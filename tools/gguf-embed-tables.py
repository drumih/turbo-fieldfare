#!/usr/bin/env python3
"""Emit GGUFIQTables.swift from llama.cpp's ggml-common.h.

The IQ grids are data, not code: 1,024 eight-byte grid entries and 256 four-byte
entries that ggml ships as C tables. They are embedded rather than fetched so the
engine has no new dependency, and generated rather than hand-copied so a typo
cannot hide in 9 KB of hex.

Usage:
    python3 tools/gguf-embed-tables.py <llama.cpp>/ggml/src/ggml-common.h
"""

import re
import sys

OUT = "sources/TinyTitan/Infrastructure/ModelIO/GGUFIQTables.swift"

TABLES = [
    ("iq2sGrid", "UInt64", "uint64_t", "iq2s_grid", 4),
    ("iq3xxsGrid", "UInt32", "uint32_t", "iq3xxs_grid", 7),
    ("ksigns", "UInt8", "uint8_t", "ksigns_iq2xs", 16),
    ("kmask", "UInt8", "uint8_t", "kmask_iq2xs", 8),
]


def values(source: str, c_type: str, name: str) -> list[str]:
    pattern = r"GGML_TABLE_BEGIN\(%s, %s, \d+\)(.*?)GGML_TABLE_END\(\)" % (c_type, name)
    match = re.search(pattern, source, re.S)
    if match is None:
        raise SystemExit("table %s not found" % name)
    body = re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", match.group(1))
    if not body:
        raise SystemExit("table %s has no values" % name)
    return body


def emit(entries: list[str], swift_type: str, per_line: int) -> str:
    lines = []
    for start in range(0, len(entries), per_line):
        chunk = entries[start : start + per_line]
        lines.append("        " + ", ".join(chunk) + ",")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    source = open(sys.argv[1], encoding="utf-8").read()
    out = [
        "// Generated by tools/gguf-embed-tables.py from llama.cpp's ggml-common.h.",
        "// Source: ggml-org/llama.cpp, MIT licence; regenerate rather than edit.",
        "//",
        "//   python3 tools/gguf-embed-tables.py <llama.cpp>/ggml/src/ggml-common.h",
        "//",
        "// The IQ grids are lookup data, not arithmetic: iq2s_grid is 8 bytes per",
        "// entry (eight 1-byte values), iq3xxs_grid 4 bytes. Decoding reads a table",
        "// entry little-endian, which is what the C reads as `const uint8_t *grid`.",
        "",
        "/// ggml IQ lookup tables. Internal: only GGUFDequant reads them.",
        "enum GGUFIQTables {",
    ]
    for swift_name, swift_type, c_type, c_name, per_line in TABLES:
        entries = values(source, c_type, c_name)
        out.append("    /// %s (%d entries)." % (c_name, len(entries)))
        out.append("    static let %s: [%s] = [" % (swift_name, swift_type))
        out.append(emit(entries, swift_type, per_line))
        out.append("    ]")
        out.append("")
    out.append("}")
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out).rstrip() + "\n")
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
